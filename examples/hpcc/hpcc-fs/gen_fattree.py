def build(name, k=4, cc_mode=3, flow_size=50_000_000, stop=0.2, enable_trace=0):
    assert k % 2 == 0 and k >= 2, "k must be even and >= 2"
    half = k // 2
    n_core = half * half
    n_agg = k * half
    n_edge = k * half
    n_host = k * half * half
    n_switch = n_core + n_agg + n_edge
    n_nodes = n_switch + n_host

    def core(i): return i                                  # 0..n_core-1
    def agg(p, i):  return n_core + p * half + i           # pod p, agg slot i
    def edge(p, j): return n_core + n_agg + p * half + j   # pod p, edge slot j
    def host(p, j, h):
        return n_core + n_agg + n_edge + (p * half + j) * half + h

    sw_ids = list(range(n_switch))
    links = []
    # agg-core: agg index i within pod connects to cores [i*half, i*half+half-1]
    for p in range(k):
        for i in range(half):
            for c in range(i * half, (i + 1) * half):
                links.append((core(c), agg(p, i), "25Gbps", "0.002ms"))
    # agg-edge: each agg connects to all edges in its pod
    for p in range(k):
        for i in range(half):
            for j in range(half):
                links.append((agg(p, i), edge(p, j), "25Gbps", "0.002ms"))
    # edge-host
    for p in range(k):
        for j in range(half):
            for h in range(half):
                links.append((edge(p, j), host(p, j, h), "100Gbps", "0.001ms"))

    topo = [f"{n_nodes} {n_switch} {len(links)}",
            " ".join(str(s) for s in sw_ids)]
    topo += [f"{a} {b} {rate} {delay} 0" for (a, b, rate, delay) in links]

    # Workload (matches the k=4 density that produced a clear multi-bottleneck signal):
    #   - First half of pods source one inter-pod flow per edge to their paired pod (p+k/2):
    #     (k/2) pods * (k/2) edges = k^2/4 inter-pod LONG flows (5-switch path each).
    #   - Each of k pods contributes one intra-pod different-edge SHORT flow (3-switch path).
    # Total flows: k^2/4 + k. For k=4 -> 4 + 4 = 8. For k=6 -> 9 + 6 = 15. For k=8 -> 16 + 8 = 24.
    flow_specs = []
    for p in range(k // 2):
        dst_pod = p + k // 2
        for j in range(half):
            s = host(p, j, 0)
            d = host(dst_pod, j, 0)
            flow_specs.append((s, d, flow_size, 0.0))
    for p in range(k):
        if half >= 2:
            s = host(p, 0, half - 1)
            d = host(p, 1, half - 1)
            flow_specs.append((s, d, flow_size, 0.0))
    flow_specs.sort(key=lambda x: x[3])
    flow_lines = [str(len(flow_specs))]
    flow_lines += [f"{s} {d} 3 100 {sz} {st:.6f}" for (s, d, sz, st) in flow_specs]

    trace = [str(n_nodes), " ".join(str(i) for i in range(n_nodes))]

    def w(rel, lines):
        path = os.path.join(HERE, rel)
        os.makedirs(os.path.dirname(path), exist_ok=True)
        with open(path, "w") as f:
            f.write("\n".join(lines) + "\n")

    w(f"topologies/{name}.txt", topo)
    w(f"flows/{name}.txt", flow_lines)
    w(f"traces/{name}_nodes.txt", trace)
    cfg = CONFIG_TEMPLATE.format(k=k, d=HPCC_DIR_REL, name=name, stop=stop,
                                 cc_mode=cc_mode, enable_trace=enable_trace)
    cfg_path = os.path.join(HERE, "configs", f"hpcc_{name}.yml")
    os.makedirs(os.path.dirname(cfg_path), exist_ok=True)
    with open(cfg_path, "w") as f:
        f.write(cfg)
    os.makedirs(os.path.join(HERE, "output", name), exist_ok=True)
    print(f"generated {name}: k={k} nodes={n_nodes} switches={n_switch} links={len(links)} "
          f"flows={len(flow_specs)} cc_mode={cc_mode}")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--k", type=int, default=4, help="fat-tree degree (even)")
    ap.add_argument("--cc-mode", type=int, default=3)
    ap.add_argument("--flow-size", type=int, default=50_000_000)
    ap.add_argument("--stop-time", type=float, default=0.2)
    ap.add_argument("--enable-trace", type=int, default=0)
    args = ap.parse_args()
    build(args.name, k=args.k, cc_mode=args.cc_mode, flow_size=args.flow_size,
          stop=args.stop_time, enable_trace=args.enable_trace)
