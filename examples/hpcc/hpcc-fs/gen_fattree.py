#!/usr/bin/env python3
"""Parameterized fat-tree generator (any even k, defaults to k=4).

Standard k-ary fat-tree:
  (k/2)^2 core switches
  k pods, each with k/2 edge + k/2 agg switches and (k/2)^2 hosts
  Cross-pod path is always edge->agg->core->agg->edge = 5 switches (== IntHeader::maxHop).

Workload: (k/2)*2 inter-pod flows + (k/2)*2 intra-pod different-edge flows + (k/2)*2 same-edge
flows, scaled with k. Hosts and ports chosen so the analyzer's BFS classifier identifies the
inter-pod flows as the multi-bottleneck ("long") class.

Node numbering (for any k):
    cores:  0 .. (k/2)^2 - 1
    aggs:   (k/2)^2 + p*(k/2) + i              (pod p, agg index i in 0..k/2-1)
    edges:  (k/2)^2 + k*(k/2) + p*(k/2) + j    (pod p, edge index j in 0..k/2-1)
    hosts:  base_host + (p*(k/2) + j)*(k/2) + h
            where base_host = (k/2)^2 + k*(k/2) + k*(k/2)
"""
import argparse
import os

HPCC_DIR_REL = "hpcc-fs"
HERE = os.path.dirname(os.path.abspath(__file__))

