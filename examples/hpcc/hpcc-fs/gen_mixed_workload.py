#!/usr/bin/env python3
"""Generate a realistic mixed-size workload on the parking-lot N=4 topology.

Pulls flow sizes (and inter-arrival pattern) from the HPCC SIGCOMM'19 Web-Search distribution
in `paper-simulations/traffic/flow_ws_30.txt`. Mapping: hosts 4,6,8,10,12 (sources) cycled,
hosts 5,7,9,11,13,14 (destinations) cycled, so the resulting flow mix exercises both the long
(multi-bottleneck) path 4->5 and short single-bottleneck paths.

Defaults: 30 flows, starts compressed into [0, 5] ms so contention is concentrated.

Reuses the parking-lot N=4 topology generated by gen_parking_lot.py (must be run first).
Produces a new config that just swaps the flow_file.
"""
import argparse
import os
import random

HERE = os.path.dirname(os.path.abspath(__file__))
HPCC_DIR = os.path.abspath(os.path.join(HERE, ".."))
WS_FLOW = os.path.join(HPCC_DIR, "paper-simulations/traffic/flow_ws_30.txt")

PARKING_TOPO_HOSTS_LONG = (5, 6)
PARKING_TOPO_HOSTS_CROSS = [(7, 8), (9, 10), (11, 12), (13, 14)]  # cross flows at N=4

