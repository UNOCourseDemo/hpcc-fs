def sample_sizes(path, n_flows, rng, max_size=None):
    """Stream the WS flow file, sample sizes uniformly (reservoir-like)."""
    sizes = []
    with open(path) as f:
        header = f.readline()
        for i, line in enumerate(f):
            cols = line.split()
            if len(cols) < 6:
                continue
            sz = int(cols[4])
            if max_size and sz > max_size:
                continue
            sizes.append(sz)
            if len(sizes) > n_flows * 200:  # sample pool 200x
                break
    rng.shuffle(sizes)
    return sizes[:n_flows]


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--name", required=True)
    ap.add_argument("--cc-mode", type=int, default=3)
    ap.add_argument("--n-flows", type=int, default=30)
    ap.add_argument("--start-window-ms", type=float, default=5.0,
                    help="spread flow starts over [0, this] ms")
    ap.add_argument("--seed", type=int, default=42)
    ap.add_argument("--max-size", type=int, default=10_000_000,
                    help="cap individual flow size (bytes); WS has very large tails")
    args = ap.parse_args()

    rng = random.Random(args.seed)
    sizes = sample_sizes(WS_FLOW, args.n_flows, rng, max_size=args.max_size)
    if not sizes:
        raise SystemExit(f"failed to sample sizes from {WS_FLOW}")

    # Map flows to host pairs: 1/4 to long path, 3/4 spread across cross paths.
    pairs = []
    for i in range(args.n_flows):
        if i % 4 == 0:
            pairs.append(PARKING_TOPO_HOSTS_LONG)  # long flow
        else:
            pairs.append(PARKING_TOPO_HOSTS_CROSS[i % len(PARKING_TOPO_HOSTS_CROSS)])

    # Random start times in [0, start_window]
    starts = sorted(rng.uniform(0.0, args.start_window_ms * 1e-3) for _ in range(args.n_flows))

    # Write flow file
    flow_lines = [str(args.n_flows)]
    for (sz, (s, d), st) in zip(sizes, pairs, starts):
        flow_lines.append(f"{s} {d} 3 100 {sz} {st:.6f}")
    flow_path = os.path.join(HERE, "flows", f"{args.name}.txt")
    os.makedirs(os.path.dirname(flow_path), exist_ok=True)
    with open(flow_path, "w") as f:
        f.write("\n".join(flow_lines) + "\n")

    # Write config
    cfg_path = os.path.join(HERE, "configs", f"hpcc_{args.name}.yml")
    os.makedirs(os.path.dirname(cfg_path), exist_ok=True)
    with open(cfg_path, "w") as f:
        f.write(CONFIG_TEMPLATE.format(cc_mode=args.cc_mode, name=args.name))

    # Stats
    n_long = sum(1 for p in pairs if p == PARKING_TOPO_HOSTS_LONG)
    print(f"generated {args.name}: n_flows={args.n_flows} long_flows={n_long} "
          f"cc_mode={args.cc_mode} sizes range=[{min(sizes)},{max(sizes)}] median={sorted(sizes)[len(sizes)//2]}")


if __name__ == "__main__":
    main()
